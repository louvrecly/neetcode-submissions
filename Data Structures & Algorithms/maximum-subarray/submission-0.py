class Solution:
    def maxSubArray(self, nums: List[int]) -> int:
        # [2 -3 4 -2 2 1 -1 4]
        # LR | [2]=2 | m: 2
        #  L  R | [2 -3]=-1 [-3]=-3 | m: 2
        #  L    R | [2 -3 4]=3 [-3 4]=1 [4]=4 | m: 4
        #  L       R | [2 -3 4 -2]=1 [-3 4 -2]=-1 [4 -2]=2 [-2]=-2 | m: 4
        #  L         R | [2 -3 4 -2 2]=3 [-3 4 -2 2]=1 [4 -2 2]=4 [-2 2]=0 [2]=2 | m: 4
        #  L           R | [2 -3 4 -2 2 1]=4 [-3 4 -2 2 1]=2 [4 -2 2 1]=5 [-2 2 1]=1 [2 1]=3 [1]=1 | m: 5
        #  L              R | [2 -3 4 -2 2 1 -1]=3 [-3 4 -2 2 1 -1]=1 [4 -2 2 1 -1]=4 [-2 2 1 -1]=0 [2 1 -1]=2 [1 -1]=0 [-1]=-1 | m: 5
        #  L                R | [2 -3 4 -2 2 1 -1 4]=7 [-3 4 -2 2 1 -1 4]=5 [4 -2 2 1 -1 4]=8 [-2 2 1 -1 4]=4 [2 1 -1 4]=6 [1 -1 4]=4 [-1 4]=3 [4]=4 | m: 8
        # [2 -3 4 -2 2 1 -1 4]
        # LR | [2] | m: 2
        #  L  R | [2-3]=-1 vs -3 [-1] | m: 2
        #  L    R | [-1+4]=3 vs 4 [4] | m: 4
        #  L       R | [4-2]=2 vs -2 [2] | m: 4
        #  L         R | [2+2]=4 vs 2 [4] | m: 4
        #  L           R | [4+1]=5 vs 1 [5] | m: 5
        #  L              R | [5-1]=4 vs -1 [4] | m: 5
        #  L                R | [4+4]=8 vs 4 [8] | m: 8
        # Time: O(n) | Space: O(1)
        localMax = nums[0]
        globalMax = nums[0]

        for i in range(1, len(nums)):
            localMax = max(nums[i], nums[i] + localMax)
            globalMax = max(localMax, globalMax)

        return globalMax
